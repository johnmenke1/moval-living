const result = businessUpdateSchema.safeParse(payload)
if (result.success) {
  console.log('OK — schema parsed. Result has all fields.')
} else {
  console.log('FAILED — Zod threw.')
  for (const issue of result.error.issues) {
    console.log(`  - path=${JSON.stringify(issue.path)} code=${issue.code} message="${issue.message}"`)
  }
}

