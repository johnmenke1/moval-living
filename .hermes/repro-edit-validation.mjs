  tagline: "",
  categoryId: "ckxxxxxxxxxxxxxxxxxxxxxxx",
  address: "12345 Main St",
  city: "Moreno Valley",
  state: "CA",
  zip: "92553",
  phone: "",
  email: "",
  website: "",
  // Auto-generated by the import route: "Business information for A-1 Auto in Moreno Valley, CA."
  // length: 53. Passes 50. Try shorter name below.
  description: "Business information for A-1 Auto in Moreno Valley, CA.",
  facebook: "",
  instagram: "",
  yelp: "",
  hours: {
    mon: { open: '11:00 AM', close: '10:00 PM', closed: false },
    tue: { open: '11:00 AM', close: '10:00 PM', closed: false },
    wed: { open: '11:00 AM', close: '10:00 PM', closed: false },
    thu: { open: '11:00 AM', close: '10:00 PM', closed: false },
    fri: { open: '11:00 AM', close: '11:00 PM', closed: false },
    sat: { open: '11:00 AM', close: '11:00 PM', closed: false },
    sun: { open: '12:00 PM', close: '9:00 PM', closed: false },
  },
