// Reproduce the validation error against the EXACT schema in
// src/lib/business-mutations.ts (copied here verbatim) with a real-looking
// "correct" business payload. This is the same call path the PUT handler
// takes — same Zod schema, same data shape.
//
// Run: node .hermes/repro-edit-validation.mjs

import { z } from 'zod'

// --- copied from src/lib/business-mutations.ts ---
const nullableText = (max) => z.union([
  z.string().trim().max(max).transform(value => value || null),
  z.null(),
]).optional()

const hoursSchema = z.record(
  z.string(),
  z.object({
    open: z.string().max(30),
    close: z.string().max(30),
    closed: z.boolean(),
  }),
).nullable().optional()

const couponSchema = z.object({
  headline: z.string().trim().min(1).max(80),
  description: z.string().trim().max(300).default(''),
  code: z.union([z.string().trim().max(20).transform(value => value || null), z.null()]).optional(),
  expiresAt: z.union([z.string().trim().max(40).transform(value => value || null), z.null()]).optional(),
}).nullable().optional()

const businessUpdateSchema = z.object({
  name: z.string().trim().min(1).max(160),
  tagline: nullableText(240),
  description: z.string().trim().min(50).max(2000),
  categoryId: z.string().trim().min(1).max(100),
  address: z.string().trim().min(1).max(240),
  city: z.string().trim().min(1).max(120),
  state: z.string().trim().length(2).transform(value => value.toUpperCase()),
  zip: z.string().trim().regex(/^\d{5}(?:-\d{4})?$/),
  phone: nullableText(50),
  email: z.union([
    z.string().trim().email().max(320).transform(value => value || null),
    z.literal('').transform(() => null),
    z.null(),
  ]).optional(),
  website: nullableText(500),
  facebook: nullableText(500),
  instagram: nullableText(500),
  yelp: nullableText(500),
  hours: hoursSchema,
  hasCoupon: z.boolean().default(false),
  coupon: couponSchema,
  googleRating: z.union([
    z.number().min(0).max(5),
    z.string().transform(v => v === '' ? null : Number(v)).pipe(z.number().min(0).max(5).nullable()),
    z.null(),
  ]).optional(),
  googleReviewCount: z.union([
    z.number().int().min(0),
    z.string().transform(v => v === '' ? null : Number(v)).pipe(z.number().int().min(0).nullable()),
    z.null(),
  ]).optional(),
  googleBusiness: nullableText(500),
}).strict()
// --- end copy ---

// Exact form payload shape from src/components/business/EditBusinessClient.tsx
